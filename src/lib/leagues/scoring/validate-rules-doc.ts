/** (1) Scorable allowlist — §7.3.3.1 guardrail 1 / §23.5's `scoring_surface`. */
function checkAllowlist(
  entries: readonly CoefficientEntry[],
  out: ScoringViolation[],
): void {
  for (const { path, key } of entries) {
    if (SCORABLE_KEYS.has(key)) continue
    const surface = SURFACE_BY_KEY.get(key)
    const why =
      surface === 'context'
        ? 'it is a context key — a raw source or an aggregate (§23.5), and paying it beside the keys derived from it is the double-count this guardrail exists to make inexpressible'
        : surface === 'reserved'
          ? 'it is a reserved key (§23.5) — deferred bonuses, placeholders and IDP are not exposed by the cohort editor'
          : 'it is not a canonical stat key at all (§23.5 STAT_KEYS)'
    out.push({
      code: 'scorable_allowlist',
      path,
      message: `Scorable allowlist (§7.3.3.1 guardrail 1): "${key}" cannot be scored — ${why}.`,
    })
  }
}

/** (5) Bounds — §7.3.3.1's per-field bounds bullet. */
function checkBounds(
  entries: readonly CoefficientEntry[],
  out: ScoringViolation[],
): void {
  for (const { path, key, value } of entries) {
    if (typeof value !== 'number' || !Number.isFinite(value)) {
      out.push({
        code: 'bounds',
        path,
        message: `Bounds (§7.3.3.1 guardrail 5): "${key}" must be a finite number; got ${describeValue(value)}.`,
      })
      continue
    }
    if (Math.abs(value) > MAX_ABS_COEFFICIENT) {
      out.push({
        code: 'bounds',
        path,
        message: `Bounds (§7.3.3.1 guardrail 5): "${key}" is ${value}; a coefficient must satisfy |coef| ≤ ${MAX_ABS_COEFFICIENT}.`,
      })
      continue
    }
    if (!isTwoDecimalMultiple(value)) {
      out.push({
        code: 'bounds',
        path,
        message: `Bounds (§7.3.3.1 guardrail 5): "${key}" is ${value}; a coefficient carries at most 2 decimal places (a multiple of ${COEFFICIENT_STEP}).`,
      })
    }
  }
}

function describeValue(value: unknown): string {
  if (typeof value === 'number') return String(value)
  if (typeof value === 'string') return JSON.stringify(value)
  return describeType(value)
}

/**
 * (2) Tier exclusivity, format-1 arm — §7.3.3.1 guardrail 2's parenthetical.
 *
 * **The reading, recorded because the spec sentence admits two.** The text is
 * *"`def_pa_*` ⊆ exactly one named platform family, shared 7-key XOR ESPN
 * 8-key, the families sharing 4 key names"*. Read literally as "a subset of
 * exactly one of the two sets", a document naming only shared key names —
 * `def_pa_0`, `def_pa_1_6`, `def_pa_7_13`, `def_pa_28_34` — would be refused
 * for being a subset of *both*, though it cannot double-pay anything: within
 * one family the tiers are non-overlapping by construction, so at most one
 * indicator is ever hot. The controlling clause is the guardrail's own stated
 * purpose two sentences earlier — *mixing* families is what must be
 * inexpressible — and the "families sharing 4 key names" parenthetical is the
 * spec telling the implementer that a key can belong to both. So the check is
 * **"some published family contains every `def_pa_*` key this document
 * names"**, which refuses exactly the mixed documents and nothing else.
 *
 * Measured, not argued: the two readings agree on every document that exists —
 * all six templates match exactly one family, and the F21 literal
 * (`def_pa_14_20` + `def_pa_18_27`) is refused under both. The divergence is
 * pinned by its own test so a ruling the other way is a one-line change.
 */
function checkFormat1TierFamilies(keys: readonly string[], out: ScoringViolation[]): void {
  const paKeys = keys.filter((key) => key.startsWith(`${DEF_PA_PREFIX}_`))
  if (paKeys.length > 0) {
    const homes = PA_FAMILY_KEY_SETS.filter(({ keys: family }) =>
      paKeys.every((key) => family.has(key)),
    )
    if (homes.length === 0) {
      out.push({
        code: 'tier_exclusivity',
        path: '',
        message: `Tier exclusivity (§7.3.3.1 guardrail 2): the points-allowed keys [${summarize(paKeys)}] are not all cut on one published family (${PA_FAMILY_KEY_SETS.map((f) => f.label).join(' or ')}). Mixing families double-pays every week that lands in the overlap — the F21 defect.`,
      })
    }
  }

  const stray = keys
    .filter((key) => key.startsWith(`${DEF_YA_PREFIX}_`))
    .filter((key) => !YA_FAMILY_KEYS.has(key))
  if (stray.length > 0) {
    out.push({
      code: 'tier_exclusivity',
      path: '',
      message: `Tier exclusivity (§7.3.3.1 guardrail 2): the yards-allowed keys [${summarize(stray)}] are not generated by the published yards-allowed cut list.`,
    })
  }
}

/**
 * (2) Tier exclusivity, format-2 arm — a document's tier keys ⊆ the set
 * generated by its OWN `tier_cuts`.
 *
 * This is the version the spec calls *inexpressible*: a format-2 document
 * carries one cut list per table, one cut list generates one non-overlapping
 * tier set, so a key the document's own cuts do not generate has no tier to
 * pay. Checked doc-wide (base AND every override, whatever position it sits
 * under), because the double-pay is a property of the document, not of one map
 * — the changelog's own words, "PA/YA **bucketization-set exclusivity**
 * doc-wide".
 *
 * A table whose cut list failed §7.3.3.1(c)'s residuals is skipped: there is no
 * trustworthy key set to compare against, and the residual violation is already
 * the document's answer.
 */
function checkFormat2TierFamilies(
  entries: readonly CoefficientEntry[],
  validCuts: { def_pa: readonly number[] | null; def_ya: readonly number[] | null },
  out: ScoringViolation[],
): void {
  for (const [prefix, cutList, table] of [
    [DEF_PA_PREFIX, validCuts.def_pa, 'points-allowed'],
    [DEF_YA_PREFIX, validCuts.def_ya, 'yards-allowed'],
  ] as const) {
    if (cutList === null) continue
    // Nothing to compare against if the document names no key in this family —
    // and generating a key set the document cannot violate is the one place a
    // long-but-legal cut list would cost real work (R595).
    if (!entries.some(({ key }) => key.startsWith(`${prefix}_`))) continue
    const generated = new Set(tierKeysFromCuts(prefix, cutList))
    for (const { path, key } of entries) {
      if (!key.startsWith(`${prefix}_`)) continue
      if (generated.has(key)) continue
      out.push({
        code: 'tier_exclusivity',
        path,
        message: `Tier exclusivity (§7.3.3.1 guardrail 2): "${key}" is not a tier this document's own ${table} cut list [${summarize(cutList)}] generates (${summarize([...generated])}). A document cannot name a tier its own cuts do not cut — that is how the F21 double-pay is made inexpressible.`,
      })
    }
  }
}

/**
 * (4) Normal form — §7.3.3.1's normal-form bullet, asked of the one
 * implementation that defines it.
 *
 * `normalizeScoringDoc` strips overrides equal to the base value and empty
 * override objects; a document is in normal form iff normalizing changes
 * nothing. Everything below is a DIFF against its output — the strip rule
 * itself (including its two designed boundaries: an override of a key absent
 * from `base` is never a no-op even at 0, and a position key outside the six is
 * preserved rather than dropped — D268(5)) lives in `rules-doc.ts` alone.
 */
function checkNormalForm(
  doc: ScoringRulesDocV2,
  overrides: ReadonlyArray<{ position: string; map: Record<string, unknown> }>,
  out: ScoringViolation[],
): void {
  const normalized = normalizeScoringDoc(doc as ScoringRulesDoc) as ScoringRulesDocV2
  const normalizedPositions = normalized.positions as Record<string, FlatScoringRules>

  for (const { position, map } of overrides) {
    const keys = Object.keys(map)

    // An override object the normal form strips ENTIRELY is reported at the
    // object path only when it is empty; when it holds keys, every one of them
    // is a no-op and each is named — a commissioner (and SE.6's route) gets
    // the same per-key message whether one key repeats the base or all of them
    // do. (`normalizeScoringDoc` keeps a key unless it exists in `base` and
    // matches it, so "did not survive" and "is a no-op" are the same fact.)
    if (!hasOwn(normalizedPositions, position) && keys.length === 0) {
      out.push({
        code: 'normal_form',
        path: `positions.${position}`,
        message: `Normal form (§7.3.3.1 guardrail 4): positions.${position} is an empty override object — the normal form carries no empty overrides, because the All-Positions switch state is derived from the document alone.`,
      })
      continue
    }

    const kept = hasOwn(normalizedPositions, position) ? normalizedPositions[position] : {}
    for (const key of keys) {
      if (hasOwn(kept, key)) continue
      out.push({
        code: 'normal_form',
        path: `positions.${position}.${key}`,
        message: `Normal form (§7.3.3.1 guardrail 4): positions.${position}.${key} repeats the base value (${JSON.stringify(doc.base[key])}), so it overrides nothing — the All-Positions switch would read OFF for a section whose values are in fact uniform.`,
      })
    }
  }
}

/**
 * §7.3.3.1(c)'s residual validation: **ascending, integers, ≥ 2 cuts, per
 * table, the two tables independent.**
 *
 * Both tables are required — `EnvelopeTierCuts`, R577/SE.1: "this league pays
 * no yards-allowed table" is expressed by paying no `def_ya_*` keys, never by
 * dropping its cut list, because guardrail 2's format-2 arm would otherwise be
 * unevaluable for that table.
 *
 * Returns each table's cut list when it is sound and `null` when it is not, so
 * guardrail 2 knows which key sets it may generate. The same three conditions
 * are `tier-cuts.ts`'s own `assertCutList` precondition, which THROWS — this is
 * the document-level, user-facing arm §7.3.3.1(5) puts here (D267(5)); calling
 * the generator on an unvalidated list is exactly the throw this module must
 * not make.
 */
function checkTierCuts(
  tierCuts: unknown,
  out: ScoringViolation[],
): { def_pa: readonly number[] | null; def_ya: readonly number[] | null } {
  const none = { def_pa: null, def_ya: null }
  if (!isPlainObject(tierCuts)) {
    out.push({
      code: 'tier_cuts',
      path: 'tier_cuts',
      message: `Tier cuts (§7.3.3.1(a)/(c)): a format-2 document carries a "tier_cuts" object with both a "${DEF_PA_PREFIX}" and a "${DEF_YA_PREFIX}" cut list; got ${describeType(tierCuts)}.`,
    })
    return none
  }

  // R588's second half, and the one a normalize-based fix would MISS:
  // `normalizeScoringDoc` passes `tier_cuts` through by REFERENCE, so a stray
  // table inside it is a fixed point of the normal form. It needs its own
  // member check, here.
  for (const table of Object.keys(tierCuts)) {
    if ((TIER_CUT_TABLES as readonly string[]).includes(table)) continue
    out.push({
      code: 'tier_cuts',
      path: `tier_cuts.${table}`,
      message: `Tier cuts (§7.3.3.1(a)/(c)): "${table}" is not a tier table — a format-2 document cuts exactly ${summarize([...TIER_CUT_TABLES])}, which are independent and additively scored. A table nothing reads is a cut list silently discarded.`,
    })
  }

  const checked: Record<string, readonly number[] | null> = { def_pa: null, def_ya: null }
  for (const table of TIER_CUT_TABLES) {
    const path = `tier_cuts.${table}`
    const list = tierCuts[table]
    if (!Array.isArray(list)) {
      out.push({
        code: 'tier_cuts',
        path,
        message: `Tier cuts (§7.3.3.1(a)/(c)): ${path} must be an ascending list of integer cut points; got ${describeType(list)}. Both tables are always written — a league that pays no ${table === 'def_pa' ? 'points-allowed' : 'yards-allowed'} table simply pays none of its keys.`,
      })
      continue
    }
    if (list.length < 2) {
      out.push({
        code: 'tier_cuts',
        path,
        message: `Tier cuts (§7.3.3.1(c)): ${path} needs at least 2 cut points to define a tier boundary; got ${list.length}.`,
      })
      continue
    }
    const badIndex = list.findIndex((cut) => !Number.isInteger(cut))
    if (badIndex >= 0) {
      out.push({
        code: 'tier_cuts',
        path,
        message: `Tier cuts (§7.3.3.1(c)): ${path} must be integers; index ${badIndex} is ${describeValue(list[badIndex])}.`,
      })
      continue
    }
    const flat = list.findIndex((cut, i) => i > 0 && (cut as number) <= (list[i - 1] as number))
    if (flat > 0) {
      out.push({
        code: 'tier_cuts',
        path,
        message: `Tier cuts (§7.3.3.1(c)): ${path} must ascend strictly — ${list[flat - 1]} then ${list[flat]} at index ${flat}. Ascending cut points are what make overlapping tiers and coverage gaps unconstructible.`,
      })
      continue
    }
    // R592 — **the points-allowed table must start at exactly 0**, which is a
    // fourth residual beyond §7.3.3.1(c)'s three, and it is D174 made
    // enforceable rather than a new rule. The PA family FLOORS at its first
    // cut (`tier-cuts.ts`'s `DEF_PA_FIRST_TIER = 'floor'`) because R58/D58
    // rules a negative points-allowed UNMAPPABLE, and §7.3.3.1(a)'s own
    // controlling clause is that the cuts reading must AGREE with today's
    // literals ("no behavior change"). A first cut anywhere but 0 breaks that
    // agreement in one direction or the other, and both directions are a lie
    // about the E61 pending badge — measured, and pinned: a first cut BELOW 0
    // pays a tier for data the derivation refuses to map, and a first cut
    // ABOVE 0 withholds the whole family on an ordinary low-scoring week
    // (PA 0/3/6 → a FALSE "waiting on data" badge on a complete week).
    // Neither moves a total; both move the only signal E61 gives. YA needs no
    // such rule — its first tier is genuinely open below (D174), because a
    // negative-total-yards game is real.
    if (table === 'def_pa' && list[0] !== 0) {
      out.push({
        code: 'tier_cuts',
        path,
        message: `Tier cuts (§7.3.3.1(c) + §7.3.3.1(a)'s derive-agreement clause): ${path} must start at 0 — a points-allowed table covers a shutout upward, and R58/D58 rules a negative points-allowed unmappable. Starting at ${list[0]} moves the E61 pending badge without moving any total. (Yards allowed has no such floor: its first tier is open below.)`,
      })
      continue
    }
    checked[table] = list as readonly number[]
  }

  return { def_pa: checked.def_pa, def_ya: checked.def_ya }
}

