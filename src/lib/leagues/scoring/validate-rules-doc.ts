/**
 * The scoring-document schema SE.6's routes parse a request body with.
 *
 * §7.3.3.1(5) is explicit that **client Zod is UX only** — the wall is the
 * server (SE.4's `scoring_rules_validate`, standing behind SE.4b's triggers).
 * So this schema deliberately contains **no rule of its own**: it hands the
 * value to `validateScoringRulesDoc` and republishes each violation as a Zod
 * issue at the same path, carrying the guardrail family in `params.guardrail`.
 *
 * That is the whole point. A hand-written `z.object({ format: z.literal(2),
 * base: z.record(z.number().min(-100).max(100)), … })` would be a second
 * implementation of families 1 and 5 in a third language, free to drift from
 * both the TS validator and the SQL mirror — and the drift would show up as a
 * route accepting a document the database then refuses, or worse, rejecting one
 * it would have accepted. `validate-rules-doc.test.ts` pins the delegation
 * (verdict and issue count identical across the whole fixture corpus), so the
 * schema cannot quietly grow an opinion.
 */
export const scoringRulesDocSchema = z
  .unknown()
  .superRefine((value, ctx) => {
    for (const violation of validateScoringRulesDoc(value).violations) {
      ctx.addIssue({
        code: 'custom',
        // Dot paths only — every segment is a registry key, a position code or
        // a document member, none of which contain a dot (pinned).
        path: violation.path === '' ? [] : violation.path.split('.'),
        message: violation.message,
        params: { guardrail: violation.code },
      })
    }
  })
  .transform((value) => value as ScoringRulesDoc)
