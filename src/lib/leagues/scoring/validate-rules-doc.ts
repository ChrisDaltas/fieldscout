/**
 * The §7.3.3.1 guardrail validator, TS side (SE.3 — F21's validator half;
 * spec §7.3.3.1's "F21 guardrails (validation LAW, not UI hope)" bullet;
 * D168's one-validator-per-language rule; D167's engine-home rule).
 *
 * ## What this module is
 *
 * §7.3.3.1 states the guardrails as a list of things a scoring document
 * **structurally cannot express** — not a list of things the editor tries not
 * to offer. This is the TS half of that law: the client's UX pre-check and the
 * service-layer pre-check, mirrored family-for-family in SQL by
 * `scoring_rules_validate(jsonb)` (SE.4), which is the wall every server write
 * path actually stands behind (SE.4b's two triggers — D175/D168). **Client Zod
 * is UX only** (§7.3.3.1(5)); nothing here is a substitute for the SQL mirror,
 * and the TS≡SQL parity fixture (D168(1)) is what stops the two drifting.
 *
 * ## The five families, in the spec's own numbering
 *
 *  1. **Scorable allowlist** — every coefficient key ∈ the registry's
 *     `scoring_surface: 'scorable'` set (§23.5 v2.11 / SE.1). Raw sources and
 *     aggregates are `context`: a document paying `def_points_allowed` *and*
 *     its derived tier buckets is the original F21 double-pay, one layer up.
 *  2. **Tier exclusivity — the F21 double-pay itself.** Format 2: the doc's
 *     `def_pa_*` keys ⊆ the set generated by its OWN `tier_cuts.def_pa`, and
 *     `def_ya_*` ⊆ the set generated by its own `tier_cuts.def_ya`. Format 1
 *     (the templates and any flat league doc): `def_pa_*` ⊆ a single published
 *     family (shared 7-key / ESPN 8-key), `def_ya_*` ⊆ the 9-key YA set.
 *     `def_pa_14_20` + `def_pa_18_27` in one document one-hot together at
 *     PA 18–20 and double-pay it — that pair is the row F21 was filed for.
 *  3. **Position scope** — `positions` keys ⊆ {QB, RB, WR, TE, K, DST}, and an
 *     override under P may name only P's own section keys (K keys only under
 *     K, D/ST keys only under DST, offense keys never under K/DST).
 *  4. **Normal form** — no no-op overrides, no empty override objects.
 *  5. **Bounds** — finite, |coef| ≤ 100, multiples of 0.01.
 *
 * Plus §7.3.3.1(c)'s **`tier_cuts` residuals** (ascending, integers, ≥ 2 cuts,
 * per table, the two tables independent) — the spec's (c) bullet, not one of
 * the five, so it is reported last.
 *
 * ## Three things this module owns on purpose, stated so they don't read as
 * accidents
 *
 * **(a) It never throws.** Its input is a JSONB blob from a route body or a
 * database column, so "this document is nonsense" is an ordinary answer, not
 * an exception. `resolveRules` and `tierKeysFromCuts` DO throw (a corrupt doc
 * reaching the engine is a programming error there), so this module checks the
 * preconditions before it composes them — which is why `tier_cuts` residuals
 * are evaluated before guardrail 2 uses them to generate a key set.
 *
 * **(b) Guardrail 4 composes `normalizeScoringDoc` — it does not re-implement
 * the strip.** The question "is this document in normal form?" is exactly "does
 * normalizing change it?", so the normal form has ONE definition
 * (`rules-doc.ts`) and this module only reports WHERE the two differ. A second
 * strip here would be the mirror D168 exists to prevent, one module over.
 *
 * **(c) Violations are ordered by the spec's own family numbering** (shape
 * first, `tier_cuts` residuals last), so `violations[0].code` is stable and
 * SE.4's SQL — which RAISEs on the FIRST violation — names the same family for
 * any document that breaks exactly one. The TS≡SQL parity fixture (SE.4(4)) is
 * built from documents that each break exactly one family for that reason.
 */

