/**
 * Validate a scoring rules document against §7.3.3.1's guardrails.
 *
 * Takes `unknown`: the caller is a route body or a `jsonb` column, and this
 * function's whole job is to be the thing that finds out. Never throws.
 *
 * A **format-1** document (a flat map with no `format` member — every shipped
 * template) is checked against the families that mean anything for a flat map:
 * the allowlist (1), the format-1 arm of tier exclusivity (2), and the bounds
 * (5). Position scope and normal form have no subject there. **That the flat
 * arm is checked at all is a deliberate reading**: §7.3.3.1's guardrail bullet
 * heads its list with "what a format-2 doc structurally cannot express", but
 * guardrail 2 spells out its own format-1 arm, D175's wall validates format-1
 * rows (`is_template = TRUE`, and any live-league-referenced row), and F21's
 * raw-source ban would be hollow if a flat document could still pay
 * `def_points_allowed` next to its derived buckets. All six templates pass
 * (pinned — the acceptance floor, SE.3(3)).
 */
export function validateScoringRulesDoc(doc: unknown): ScoringValidationResult {
  const shape: ScoringViolation[] = []
  const allowlist: ScoringViolation[] = []
  const exclusivity: ScoringViolation[] = []
  const positionScope: ScoringViolation[] = []
  const normalForm: ScoringViolation[] = []
  const bounds: ScoringViolation[] = []
  const cuts: ScoringViolation[] = []

  const collect = (): ScoringValidationResult => {
    const violations = [
      ...shape,
      ...allowlist,
      ...exclusivity,
      ...positionScope,
      ...normalForm,
      ...bounds,
      ...cuts,
    ]
    if (violations.length > MAX_REPORTED_VIOLATIONS) {
      return {
        valid: false,
        violations: [
          ...violations.slice(0, MAX_REPORTED_VIOLATIONS),
          {
            code: 'document_shape',
            path: '',
            message: `Document shape (§7.3.3.1): this document has ${violations.length} problems; the first ${MAX_REPORTED_VIOLATIONS} are listed above (R595 — the answer is capped, the verdict is not).`,
          },
        ],
      }
    }
    return { valid: violations.length === 0, violations }
  }

  // ── The front door ──────────────────────────────────────────────────────
  if (!isPlainObject(doc)) {
    shape.push({
      code: 'document_shape',
      path: '',
      message: `Document shape (§7.3.3.1): a scoring rules document must be a JSON object; got ${describeType(doc)}.`,
    })
    return collect()
  }

  const isFormat2 = hasOwn(doc, SCORING_DOC_FORMAT_KEY)

  // ── Format 1: the flat map ──────────────────────────────────────────────
  if (!isFormat2) {
    // An envelope whose `format` member was dropped reads as a flat map whose
    // keys happen to be "base", "positions" and "tier_cuts" — and the answer
    // was six allowlist violations naming nothing a commissioner could act on
    // (R597). The document says what it is; the refusal should too.
    const envelopeMembers = Object.keys(doc).filter(
      (key) => key !== SCORING_DOC_FORMAT_KEY && ENVELOPE_MEMBERS.has(key),
    )
    if (envelopeMembers.length > 0) {
      shape.push({
        code: 'document_shape',
        path: '',
        message: `Document shape (§7.3.3.1): this document carries no "format" member, so it reads as a flat format-1 map — but it holds ${summarize(envelopeMembers)}, which are format-2 envelope members. Add "format": ${SCORING_DOC_FORMAT_2}, or make it a genuine flat map of coefficients.`,
      })
    }

    const entries = coefficientEntries(doc, [], '')
    checkAllowlist(entries, allowlist)
    checkBounds(entries, bounds)
    checkFormat1TierFamilies(Object.keys(doc), exclusivity)
    return collect()
  }

  // ── Format 2: the envelope ──────────────────────────────────────────────
  const format = doc[SCORING_DOC_FORMAT_KEY]
  if (format !== SCORING_DOC_FORMAT_2) {
    // Never fall through to a plausible reading of an unknown version: a
    // `format: 3` document read as flat, or as base-only, scores an entire
    // league wrong with no error anywhere (CLAUDE.md's never-let-"nothing
    // happened"-mean-"it worked" rule; the same refusal `resolveRules` makes,
    // here as a violation rather than a throw).
    shape.push({
      code: 'document_shape',
      path: SCORING_DOC_FORMAT_KEY,
      message:
        format === 1
          ? // The one version number that needs its own sentence (R597): the
            // first cut of this message refused a document "for declaring
            // format 1" while saying in the same breath that it validates
            // format 1. Both halves are true and the combination is nonsense —
            // format 1 IS the flat map, identified by carrying NO version
            // member at all (§7.3.3.1: "no `format` member — the discriminator
            // is unambiguous"), so a document that names version 1 is not one.
            `Document shape (§7.3.3.1): this document declares format 1 — but format 1 IS the flat map, identified by carrying NO "format" member at all, so a document that names the version is not one. Drop the "format" member for a flat map, or use format ${SCORING_DOC_FORMAT_2}'s envelope.`
          : `Document shape (§7.3.3.1): this document declares format ${JSON.stringify(format)}, which this build cannot validate — it knows the flat map (no "format" member) and format ${SCORING_DOC_FORMAT_2}. A future format is a future validator, never a silent pass.`,
    })
    return collect()
  }

  // §7.3.3.1's printed shape has exactly four members, and a document that
  // carries a FIFTH is not a document with a harmless extra — it is almost
  // always a member the writer believed was load-bearing (R588). Nothing else
  // in this module would ever look at it: every family reads `base` and
  // `positions`, so `postions: {…}` — one transposed letter — used to validate
  // clean while `resolveRules` returned the base values and the commissioner's
  // entire override map evaporated on save. That is CLAUDE.md's
  // never-let-"nothing happened"-mean-"it worked" and §7.3.3.1(5)'s "never a
  // silently-ignored key", so an unenumerated member is refused BY NAME.
  for (const member of Object.keys(doc)) {
    if (ENVELOPE_MEMBERS.has(member)) continue
    shape.push({
      code: 'document_shape',
      path: member,
      message: `Document shape (§7.3.3.1's printed shape): "${member}" is not a member of a format-2 scoring document, which carries exactly ${summarize([...ENVELOPE_MEMBERS])}. A member nothing reads is a value silently discarded on save — coefficients belong in "base" or under a position.`,
    })
  }

  const base = doc.base
  if (!isPlainObject(base)) {
    shape.push({
      code: 'document_shape',
      path: 'base',
      message: `Document shape (§7.3.3.1's printed shape): a format-2 scoring document needs a "base" object; got ${describeType(base)}.`,
    })
  }
  const positions = doc.positions
  if (!isPlainObject(positions)) {
    shape.push({
      code: 'document_shape',
      path: 'positions',
      message: `Document shape (§7.3.3.1's printed shape): a format-2 scoring document needs a "positions" object; got ${describeType(positions)}.`,
    })
  }

  // §7.3.3.1(c) residuals, evaluated HERE because guardrail 2 generates its
  // key sets from them — a malformed cut list must produce a violation, never
  // a throw out of `tierKeysFromCuts`, and never a generated key set nobody
  // should trust.
  const validCuts = checkTierCuts(doc.tier_cuts, cuts)

  if (!isPlainObject(base) || !isPlainObject(positions)) return collect()

  // Overrides, in document order. A non-object override is a shape violation
  // (and stops guardrail 4, which would throw on it).
  const overrides: Array<{ position: string; map: Record<string, unknown> }> = []
  let everyOverrideIsAnObject = true
  for (const position of Object.keys(positions)) {
    const override = positions[position]
    if (!isPlainObject(override)) {
      everyOverrideIsAnObject = false
      shape.push({
        code: 'document_shape',
        path: `positions.${position}`,
        message: `Document shape (§7.3.3.1's printed shape): a position override must be an object of coefficients; positions.${position} is ${describeType(override)}.`,
      })
      continue
    }
    overrides.push({ position, map: override })
  }

  const entries = coefficientEntries(base, overrides, 'base')

  // (1) Scorable allowlist.
  checkAllowlist(entries, allowlist)

  // (2) Tier exclusivity — the format-2 arm: against the document's OWN cuts.
  checkFormat2TierFamilies(entries, validCuts, exclusivity)

  // (3) Position scope.
  for (const { position, map } of overrides) {
    if (!isScoringPosition(position)) {
      positionScope.push({
        code: 'position_scope',
        path: `positions.${position}`,
        message: `Position scope (§7.3.3.1 guardrail 3): "${position}" is not one of the six scored positions ${SCORING_POSITIONS.join(', ')}.`,
      })
      continue
    }
    const legal = POSITION_KEY_SETS[position]
    for (const key of Object.keys(map)) {
      if (legal.has(key)) continue
      // A key that is not scorable at all is already guardrail 1's rejection;
      // saying it twice would make the parity fixture's first-violation
      // contract ambiguous for no gain.
      if (!SCORABLE_KEYS.has(key)) continue
      positionScope.push({
        code: 'position_scope',
        path: `positions.${position}.${key}`,
        message: `Position scope (§7.3.3.1 guardrail 3): "${key}" is not scored for ${position} — it belongs to ${whereKeyBelongs(key)}. An override may only name its own position's section keys.`,
      })
    }
  }

  // (4) Normal form — asked of `normalizeScoringDoc`, never re-implemented.
  if (everyOverrideIsAnObject) {
    checkNormalForm(doc as unknown as ScoringRulesDocV2, overrides, normalForm)
  }

  // (5) Bounds.
  checkBounds(entries, bounds)

  return collect()
}

/** `typeof`, but useful in a message: arrays and null read as themselves. */
function describeType(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'an array'
  if (value === undefined) return 'nothing'
  return `a ${typeof value}`
}

/** Which position pages DO carry `key` — for guardrail 3's message. */
function whereKeyBelongs(key: string): string {
  const homes = SCORING_POSITIONS.filter((position) =>
    POSITION_KEY_SETS[position].has(key),
  )
  if (homes.length === 0) return 'no position page'
  if (homes.length === SCORING_POSITIONS.length) return 'every position'
  return homes.join('/')
}

