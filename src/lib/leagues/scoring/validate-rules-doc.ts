/** The four members §7.3.3.1's printed shape defines, and the two tables its
 *  `tier_cuts` defines — the closed sets R588's member check tests against. */
const ENVELOPE_MEMBERS: ReadonlySet<string> = new Set([
  SCORING_DOC_FORMAT_KEY,
  'base',
  'positions',
  'tier_cuts',
])
const TIER_CUT_TABLES: readonly ['def_pa', 'def_ya'] = ['def_pa', 'def_ya']

const hasOwn = (object: object, key: string): boolean =>
  Object.prototype.hasOwnProperty.call(object, key)

const isPlainObject = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value)

const isScoringPosition = (key: string): key is ScoringPosition =>
  (SCORING_POSITIONS as readonly string[]).includes(key)

/** A coefficient entry to check, with the dot path it lives at. */
interface CoefficientEntry {
  path: string
  key: string
  value: unknown
}

/**
 * Every coefficient in the document, base first then overrides in document
 * order — the order guardrails 1 and 5 report in.
 *
 * `basePath` is `'base'` for the envelope and `''` for a flat format-1
 * document, whose coefficients live at the top level: reporting a flat map's
 * problem at `base.pass_yardz` would name a member the document does not have,
 * and SE.6's route surfaces these paths as form fields.
 */
function coefficientEntries(
  base: Record<string, unknown>,
  overrides: ReadonlyArray<{ position: string; map: Record<string, unknown> }>,
  basePath: string,
): CoefficientEntry[] {
  const entries: CoefficientEntry[] = Object.keys(base).map((key) => ({
    path: basePath === '' ? key : `${basePath}.${key}`,
    key,
    value: base[key],
  }))
  for (const { position, map } of overrides) {
    for (const key of Object.keys(map)) {
      entries.push({ path: `positions.${position}.${key}`, key, value: map[key] })
    }
  }
  return entries
}

