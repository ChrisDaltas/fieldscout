/**
 * playoffs-api-db.test.ts — L.D5.5's stack half for `GET /api/leagues/[id]/playoffs`
 * at the SERVICE layer (`readPlayoffBracket`) and the standings route's
 * projected arm (`readStandings(…, { view: 'projected' })`) against the
 * LOCAL Supabase stack through PostgREST — the production wire path — with
 * real signed-in clients (the `inseason-reads-api-db.test.ts` shape).
 *
 * pgTAP 066 proves 118's engine DB-side (the pairing rule, the rollover,
 * the rebuild, the verdicts). What THIS suite proves is the layer it does
 * not touch:
 *   - the auth matrix on the member read: a NON-MEMBER gets the family's
 *     no-leak 403 (118's in-body 42501), a nonexistent league the same 403
 *     for a member, a SOFT-DELETED league the ONE 404 copy (R812);
 *   - the PROJECTED document over 118's REAL rows: a league whose season
 *     was generated by `league_generate_schedule` (110 — 14 regular + 3
 *     playoff `league_weeks`, the 8-team defaults: `playoff_teams` 6,
 *     bracket 8, 3 rounds) reads `view: projected` with round 1 seeded
 *     from the projected table (2 byes, 2 games), the basis named, and
 *     the rollover NULL on the wire (the synthetic calendar records no
 *     `last_game_ends_at` — F238's posture reaches the client as `null`);
 *   - **F247(b) on the bracket**: playoff rows PLANTED with seeds (the
 *     engine's shape — a row with seeds is the engine's, D318(5)) render
 *     `home_total` as `101.25` and a bye's as `0` on the wire, and the
 *     service hands the UI ONE kind of number; a NULL week score stays
 *     NULL (E61); `decided_by` is 118's verdict;
 *   - a playoff row WITHOUT seeds is counted as `foreign_rows` and never
 *     read as a game;
 *   - the projected standings arm: `projected: true` / `weeks_projected`
 *     through the route's query, the final read `projected: false`, and a
 *     `?view=` outside the enum a 400.
 *
 * Requires the local stack — D59(5) precedent; FAILS loudly when the
 * stack is down, never skips (§4.3).
 *
 * CALENDAR (F215/F226): the league lives on `SYNTHETIC_SEASON` (2099); NO
 * `nfl_games` rows are placed and NO `nfl_weeks` instant is written —
 * nothing here evaluates a kickoff or drives a job. The planted playoff
 * rows are `scheduled` rows with scores, exactly what the read model
 * reads (066 I-series' shape).
 *
 * Determinism: FIXED emails/usernames/action_ids + cleanup-first. Action-id
 * prefix `b01` — this suite owns it (the D108(14) registry: af0–aff and
 * b00 taken, b01 measured free 2026-09-08).
 */
