describe('GET …/playoffs — the auth matrix (118 in-body; the family’s posture)', () => {
  it('a NON-MEMBER is refused by 118 in-body (42501) and the service answers the family’s no-leak 403', async () => {
    expect(await readPlayoffBracket(outsiderClient, leagueId)).toStrictEqual({ status: 403, body: { error: INSEASON_READ_FORBIDDEN_MESSAGE } })
  })

  it('a nonexistent league answers a member the same 403 — the membership check precedes the lookup', async () => {
    expect(await readPlayoffBracket(managerClient, NO_SUCH_LEAGUE)).toStrictEqual({ status: 403, body: { error: INSEASON_READ_FORBIDDEN_MESSAGE } })
  })
})

describe('GET …/playoffs — the PROJECTED document over 118’s real rows (Q39 (E): "if the playoffs started today")', () => {
  it('a member reads view: projected — round 1 seeded from the projected table (2 byes, 2 games), the basis named, the rollover NULL on the wire (F238), three unbuilt rounds', async () => {
    const result = await readPlayoffBracket(managerClient, leagueId)
    expect(result.status, errorText(result)).toBe(200)
    const doc = result.body as unknown as PlayoffBracketDoc
    expect(doc.kind).toBe('bracket')
    expect(doc.view).toBe('projected')
    expect(doc.status).toBe('in_season')
    expect(doc.playoff_teams).toBe(6)
    expect(doc.bracket_size).toBe(8)
    expect(doc.rounds).toBe(3)
    expect(doc.weeks_per_round).toBe(1)
    expect(doc.reseed).toBe(true)
    expect(doc.regular_season).toEqual({ first_week: 1, last_week: 14 })
    expect(doc.playoff_start_week).toBe(15)
    expect(doc.regular_season_rolled).toBe(false)
    expect(doc.regular_season_final).toBe(false)
    // The ONE instant: the synthetic calendar records no last game end —
    // the wire carries `null`, and the UI names the event (never a clock).
    expect(doc.rollover_week).toBe(14)
    expect(doc.rollover_at).toBeNull()
    expect(typeof doc.corrections_close_at).toBe('string')
    expect(doc.next_round).toBe(1)
    expect(doc.champion_team_id).toBeNull()
    expect(doc.bracket_champion_team_id).toBeNull()

    // Round 1 from the projected table: 8 seated teams → 6 seeds; byes to
    // seeds 1–2, then 3v6 and 4v5 (rider (i)) — the ENGINE's pairing.
    expect(doc.projection_basis).toEqual({ projected: true, weeks_final: 0, weeks_projected: 0, seeded: 6, reason: 'no_final_weeks' })
    expect(doc.projected_round_1).not.toBeNull()
    const pairs = doc.projected_round_1!
    expect(pairs).toHaveLength(4)
    expect(pairs.map((p) => [p.home.seed, p.away?.seed ?? null])).toEqual([
      [1, null],
      [2, null],
      [3, 6],
      [4, 5],
    ])
    for (const p of pairs) {
      expect(teamIds).toContain(p.home.team_id)
      if (p.away) expect(teamIds).toContain(p.away.team_id)
    }
    expect(new Set(pairs.flatMap((p) => [p.home.team_id, p.away?.team_id]).filter(Boolean)).size).toBe(6)

    expect(doc.round_list.map((r) => [r.round, r.built, r.expected_games, r.foreign_rows, r.weeks.map((w) => w.week)])).toEqual([
      [1, false, 4, 0, [15]],
      [2, false, 2, 0, [16]],
      [3, false, 1, 0, [17]],
    ])
  })

  it('the projected STANDINGS arm through the route’s query: projected: true; the final read projected: false; a view outside the enum is a 400', async () => {
    const projected = await readStandings(managerClient, leagueId, { view: 'projected' })
    expect(projected.status, errorText(projected)).toBe(200)
    const pdoc = projected.body as unknown as LeagueStandings
    expect(pdoc.projected).toBe(true)
    expect(pdoc.weeks_projected).toBe(0) // no OPEN week: every league_week is `upcoming`
    expect(pdoc.standings).toHaveLength(8)
    expect(pdoc.reason).toBe('no_final_weeks')

    const final = await readStandings(managerClient, leagueId)
    expect(final.status).toBe(200)
    const fdoc = final.body as unknown as LeagueStandings
    expect(fdoc.projected).toBe(false)
    expect(fdoc.weeks_projected).toBe(0)
    // The two tables agree with no open week — the projection adds nothing.
    expect(pdoc.standings.map((r) => r.team_id)).toEqual(fdoc.standings.map((r) => r.team_id))

    const bogus = await readStandings(managerClient, leagueId, { view: 'live' })
    expect(bogus.status).toBe(400)
    // The outsider is refused on the projected arm too (118's wrapper carries 117's member check).
    expect(await readStandings(outsiderClient, leagueId, { view: 'projected' })).toStrictEqual({ status: 403, body: { error: INSEASON_READ_FORBIDDEN_MESSAGE } })
  })
})

describe('GET …/playoffs — a BUILT round over planted engine rows (F247(b) on the bracket; E61; D318(5))', () => {
  const planted: string[] = []

  afterAll(async () => {
    if (planted.length > 0) await service.from('matchups').delete().in('id', planted)
  })

  it('rows WITH seeds are the engine’s: the totals arrive as ONE kind of number, a NULL score stays NULL, decided_by is 118’s; a row WITHOUT seeds is a foreign row, counted and never read', async () => {
    const [a, b, c, d, e, f, g, h] = teamIds
    // Round 1 in week 15 (the plan's first playoff week): A bye (seed 1), B
    // bye (seed 2), C(3) v F(6) 101.25–98.10, D(4) v E(5) 90.00–NULL (E's
    // score pending). Plus a FOREIGN row (no seeds) in the same week.
    const { data: rows, error } = await service
      .from('matchups')
      .insert([
        { league_id: leagueId, season: SYNTHETIC_SEASON, week: 15, round_type: 'playoff', home_team_id: a, away_team_id: null, home_seed: 1, away_seed: null, status: 'scheduled' },
        { league_id: leagueId, season: SYNTHETIC_SEASON, week: 15, round_type: 'playoff', home_team_id: b, away_team_id: null, home_seed: 2, away_seed: null, status: 'scheduled' },
        { league_id: leagueId, season: SYNTHETIC_SEASON, week: 15, round_type: 'playoff', home_team_id: c, away_team_id: f, home_seed: 3, away_seed: 6, home_score: 101.25, away_score: 98.1, status: 'scheduled' },
        { league_id: leagueId, season: SYNTHETIC_SEASON, week: 15, round_type: 'playoff', home_team_id: d, away_team_id: e, home_seed: 4, away_seed: 5, home_score: 90, away_score: null, status: 'scheduled' },
        { league_id: leagueId, season: SYNTHETIC_SEASON, week: 15, round_type: 'playoff', home_team_id: g, away_team_id: h, status: 'scheduled' },
      ])
      .select('id')
    expect(error?.message ?? null).toBeNull()
    planted.push(...(rows ?? []).map((r) => r.id))
    expect(planted).toHaveLength(5)

    const result = await readPlayoffBracket(managerClient, leagueId)
    expect(result.status, errorText(result)).toBe(200)
    const doc = result.body as unknown as PlayoffBracketDoc
    expect(doc.view).toBe('bracket') // round 1 exists ⇒ no projection (118 §9)
    expect(doc.projected_round_1).toBeNull()
    expect(doc.next_round).toBe(2)
    const r1 = doc.round_list[0]
    expect(r1.built).toBe(true)
    expect(r1.foreign_rows).toBe(1)
    expect(r1.games).toHaveLength(4)
    expect(r1.games.map((x) => [x.home_seed, x.away_seed, x.decided_by, x.final])).toEqual([
      [1, null, 'bye', false],
      [2, null, 'bye', false],
      [3, 6, 'points', false],
      [4, 5, 'points', false],
    ])
    // F247(b): the numeric scale collapses to ONE JS kind through the service.
    const game = r1.games[2]
    expect(game.home_total).toBe(101.25)
    expect(game.away_total).toBe(98.1)
    expect(typeof game.home_total).toBe('number')
    expect(r1.games[0].home_total).toBe(0)
    expect(typeof r1.games[0].home_total).toBe('number')
    expect(game.weeks).toHaveLength(1)
    expect(game.weeks[0].home_score).toBe(101.25)
    // E61: E's pending score is NULL on the wire and NULL after the service — never 0.00.
    const pending = r1.games[3]
    expect(pending.weeks[0].away_score).toBeNull()
    expect(pending.away_total).toBe(0) // 118's sum COALESCEs a NULL to 0 for the verdict; the CELL stays null
    expect(pending.winner_team_id).toBe(d)
    // The foreign pair never appears as a game.
    for (const x of r1.games) {
      expect([g, h]).not.toContain(x.home_team_id)
      expect([g, h]).not.toContain(x.away_team_id)
    }
    expect(r1.survivors.map((s) => s.seed)).toEqual([1, 2, 3, 4])
    expect(doc.entrants_next?.map((s) => s.seed)).toEqual([1, 2, 3, 4])
  })

  it('the raw RPC really does render the two scales differently on the WIRE (R601: raw bytes) — which is why the service normalises', async () => {
    const { data: session } = await managerClient.auth.getSession()
    const response = await fetch(`${LOCAL_URL}/rest/v1/rpc/league_playoff_bracket`, {
      method: 'POST',
      headers: { apikey: LOCAL_ANON_KEY, Authorization: `Bearer ${session.session?.access_token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ p_league_id: leagueId }),
    })
    expect(response.status).toBe(200)
    const raw = await response.text()
    // The SUMMED figure carries the `round(…, 2)` scale (`90.00`, `0.00`)
    // while the raw column renders as stored (`90`, `101.25`, `98.1`) — two
    // renderings of one score, which is why the service normalises rather
    // than trusts; and a NULL cell is `null`, never `0`.
    expect(raw).toMatch(/"home_total":\s*90\.00\b/)
    expect(raw).toMatch(/"home_total":\s*0\.00\b/)
    expect(raw).toMatch(/"home_score":\s*90[,}]/)
    expect(raw).toMatch(/"away_score":\s*98\.1[,}]/)
    expect(raw).toMatch(/"away_score":\s*null/)
  })
})

describe('a SOFT-DELETED league answers a MEMBER the ONE 404 copy after the membership check, and a NON-MEMBER the same 403 (R812)', () => {
  it('playoffs + the projected standings arm', async () => {
    const { error: deleteError } = await service.from('leagues').update({ deleted_at: '2099-01-01T00:00:00+00:00' }).eq('id', leagueId)
    expect(deleteError).toBeNull()
    try {
      const gone = { status: 404, body: { error: INSEASON_LEAGUE_GONE_MESSAGE } }
      const playoffs = await readPlayoffBracket(managerClient, leagueId)
      expect(playoffs).toStrictEqual(gone)
      expect(errorText(playoffs)).not.toContain('not found')
      expect(await readStandings(managerClient, leagueId, { view: 'projected' })).toStrictEqual(gone)
      const forbidden = { status: 403, body: { error: INSEASON_READ_FORBIDDEN_MESSAGE } }
      expect(await readPlayoffBracket(outsiderClient, leagueId)).toStrictEqual(forbidden)
    } finally {
      const { error: restoreError } = await service.from('leagues').update({ deleted_at: null }).eq('id', leagueId)
      expect(restoreError).toBeNull()
    }
    expect((await readPlayoffBracket(managerClient, leagueId)).status).toBe(200)
  })
})
